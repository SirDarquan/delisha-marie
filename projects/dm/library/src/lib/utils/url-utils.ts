import { Breadcrumbs } from '../types/recipe';

/**
 * Safely removes leading slashes from a string without using regex (preventing ReDoS).
 */
export function trimLeadingSlashes(str: string): string {
  let start = 0;
  while (start < str.length && str.codePointAt(start) === 47 /* '/' */) {
    start++;
  }
  return str.substring(start);
}

/**
 * Safely removes trailing slashes from a string without using regex (preventing ReDoS).
 */
export function trimTrailingSlashes(str: string): string {
  let end = str.length;
  while (end > 0 && str.codePointAt(end - 1) === 47 /* '/' */) {
    end--;
  }
  return str.substring(0, end);
}

/**
 * Safely removes both leading and trailing slashes from a string without using regex.
 */
export function trimSlashes(str: string): string {
  return trimTrailingSlashes(trimLeadingSlashes(str));
}

/**
 * Checks if a breadcrumb trail is a standard recipe trail (not automated and not 'The Best Recipes').
 */
export function isStandardTrail(trail: { label?: string; url?: string }[]): boolean {
  if (trail.length === 0) return false;
  const isHome = trail[0]?.url === '/';
  const isRecipes = trail[1]?.url === '/recipes';
  const isBest = trail.some((t) => t.url?.includes('/the-best-recipes'));
  const isAutoGenerated = trail.some(
    (t) =>
      t.url?.includes('/method') ||
      t.url?.includes('/special-diets') ||
      t.url?.includes('/holidays'),
  );
  return isHome && isRecipes && !isBest && !isAutoGenerated;
}

/**
 * Formats the recipe URL trail leaf node cleanly and consistently.
 * Eliminates duplicate logic in breadcrumb-board.ts.
 */
export function getCleanRecipeUrl(slug: string): string {
  const cleanedSlug = trimLeadingSlashes(slug).replace(/^recipe\//i, '');
  return `/recipe/${trimLeadingSlashes(cleanedSlug)}`;
}

/**
 * Converts a string to a URL-friendly slug.
 * Example: "Valentine's Day" -> "valentines-day"
 */
export function slugify(text: string): string {
  return text
    .toString()
    .toLowerCase()
    .trim()
    .replaceAll("'s", 's') // Handle possessives: Valentine's -> valentines
    .replaceAll(/[^a-z0-9 -]/g, '') // Remove special characters
    .replaceAll(/\s+/g, '-') // Replace spaces with -
    .replaceAll(/-+/g, '-'); // Remove duplicate hyphens
}

/**
 * Best-effort reversal of a slug to a display name.
 * Example: "independence-day" -> "Independence Day"
 */
export function deslugify(slug: string): string {
  const specialCases: Record<string, string> = {
    valentines: "Valentine's",
    patricks: "Patrick's",
    st: 'St.',
  };

  return slug
    .split('-')
    .map((word) => {
      const lower = word.toLowerCase();
      // Check special cases first
      if (specialCases[lower]) {
        return specialCases[lower];
      }

      // Special cases for common words that shouldn't be capitalized
      const lowercaseWords = ['and', 'or', 'the', 'of', 'in', 'with', 'for'];
      if (lowercaseWords.includes(lower)) {
        return lower;
      }
      return word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join(' ')
    .replace(/^([a-z])/, (match) => match.toUpperCase()); // Always capitalize first word
}

/**
 * Strategy for Holiday and Category URLs:
 * 1. Base path: /holiday/ or /recipes/ or /methods/
 * 2. Slug: generated from the name
 * 3. Result: lowercase, kebab-case
 */
export function generateUrl(basePath: string, name: string): string {
  const cleanBase = basePath.endsWith('/') ? basePath : `${basePath}/`;
  return `${cleanBase}${slugify(name)}`;
}

/**
 * Formats multiple trails of board pieces into a unified Breadcrumbs structure.
 * Eliminates duplicate breadcrumb mapping logic in breadcrumb-board.ts.
 */
export function mapTrailsToBreadcrumbs(
  boardPiecesList: { name: string; url: string }[][],
  recipeTitle: string,
  recipeSlug: string,
): Breadcrumbs {
  const mappedItems = boardPiecesList.map((trail) => {
    const title = recipeTitle || 'Untitled';
    let finalTrail = trail;
    if (recipeSlug) {
      const recipeUrl = getCleanRecipeUrl(recipeSlug);
      finalTrail = [...trail, { name: title, url: recipeUrl }];
    }
    return finalTrail.map((p) => ({
      label: p.name,
      url: p.url,
    }));
  });

  return {
    main: 0,
    items: mappedItems,
  };
}

/**
 * Extracts a YouTube video ID from a URL.
 * Supports various YouTube URL formats.
 */
export function extractYouTubeVideoId(url: string | null | undefined): string | null {
  if (!url) return null;
  const regex = /(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?(?:.*&)?v=))([^&]{11})/;
  const match = regex.exec(url);
  return match ? match[1] : url.trim();
}
